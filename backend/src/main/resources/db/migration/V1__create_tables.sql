CREATE INDEX IDX_DOCTOR_ID_IS_CANCELLED ON APPOINTMENTS (DOCTOR_ID, IS_CANCELLED);

CREATE INDEX IDX_IS_CONFIRMED_DATE ON APPOINTMENTS (IS_CONFIRMED, APPOINTMENT_DATE);

CREATE INDEX IDX_PATIENT_ID_IS_CANCELLED ON APPOINTMENTS (PATIENT_ID, IS_CANCELLED);

ALTER TABLE APPOINTMENTS
    ADD CONSTRAINT FK_APPOINTMENTS_ON_DOCTOR FOREIGN KEY (DOCTOR_ID) REFERENCES USERS (USER_ID);

ALTER TABLE APPOINTMENTS
    ADD CONSTRAINT FK_APPOINTMENTS_ON_INVOICE FOREIGN KEY (INVOICE_ID) REFERENCES INVOICES (INVOICE_ID);

ALTER TABLE APPOINTMENTS
    ADD CONSTRAINT FK_APPOINTMENTS_ON_PATIENT FOREIGN KEY (PATIENT_ID) REFERENCES USERS (USER_ID);

