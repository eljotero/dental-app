CREATE SEQUENCE IF NOT EXISTS USER_ID_SEQ START WITH 50 INCREMENT BY 50;

CREATE TABLE USERS
(
    USER_ID                    BIGINT       NOT NULL,
    FIRST_NAME                 VARCHAR(255) NOT NULL,
    LAST_NAME                  VARCHAR(255) NOT NULL,
    EMAIL                      VARCHAR(255) NOT NULL,
    PASSWORD                   VARCHAR(255) NOT NULL,
    PHONE_NUMBER               VARCHAR(255) NOT NULL,
    SEX                        BOOLEAN      NOT NULL,
    PERSONAL_ID_NUMBER         VARCHAR(255) NOT NULL,
    COUNTRY                    VARCHAR(255) NOT NULL,
    CITY                       VARCHAR(255) NOT NULL,
    ADDRESS_LINE               VARCHAR(255) NOT NULL,
    USER_TYPE                  VARCHAR(255) NOT NULL,
    ZIP_CODE                   VARCHAR(255) NOT NULL,
    DATE_OF_BIRTH              DATE         NOT NULL,
    IS_ENABLED                 BOOLEAN      NOT NULL,
    IS_NON_EXPIRED             BOOLEAN      NOT NULL,
    IS_NON_LOCKED              BOOLEAN      NOT NULL,
    IS_CREDENTIALS_NON_EXPIRED BOOLEAN      NOT NULL,
    LANGUAGE                   VARCHAR(255) NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID)
);

CREATE INDEX IDX_EMAIL ON USERS (EMAIL);

CREATE INDEX IDX_EMAIL_USER_TYPE ON USERS (EMAIL, USER_TYPE);

CREATE INDEX IDX_USER_TYPE ON USERS (USER_TYPE);

CREATE SEQUENCE IF NOT EXISTS TOKEN_ID_SEQ START WITH 50 INCREMENT BY 50;

CREATE TABLE TOKENS
(
    TOKEN_ID     BIGINT                      NOT NULL,
    TOKEN        VARCHAR(255)                NOT NULL,
    CREATED_AT   TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    EXPIRES_AT   TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONFIRMED_AT TIMESTAMP WITHOUT TIME ZONE,
    USER_ID      BIGINT                      NOT NULL,
    CONSTRAINT PK_TOKENS PRIMARY KEY (TOKEN_ID)
);

CREATE INDEX IDX_TOKEN ON TOKENS (TOKEN);

ALTER TABLE TOKENS
    ADD CONSTRAINT FK_TOKENS_ON_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID);

