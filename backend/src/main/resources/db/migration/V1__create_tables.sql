CREATE TABLE APPOINTMENTS
(
    APPOINTMENT_ID         BIGINT                 NOT NULL,
    PATIENT_ID             BIGINT                 NOT NULL,
    DOCTOR_ID              BIGINT                 NOT NULL,
    APPOINTMENT_DATE       DATE                   NOT NULL,
    APPOINTMENT_START_TIME TIME WITHOUT TIME ZONE NOT NULL,
    APPOINTMENT_END_TIME   TIME WITHOUT TIME ZONE NOT NULL,
    IS_CONFIRMED           BOOLEAN                NOT NULL,
    IS_CANCELLED           BOOLEAN                NOT NULL,
    DESCRIPTION            VARCHAR(255),
    INVOICE_ID             BIGINT,
    VERSION                BIGINT,
    CONSTRAINT PK_APPOINTMENTS PRIMARY KEY (APPOINTMENT_ID)
);

ALTER TABLE APPOINTMENTS
    ADD CONSTRAINT UC_APPOINTMENTS_INVOICE UNIQUE (INVOICE_ID);

CREATE INDEX IDX_DATE_IS_CANCELLED ON APPOINTMENTS (APPOINTMENT_DATE, IS_CANCELLED);

